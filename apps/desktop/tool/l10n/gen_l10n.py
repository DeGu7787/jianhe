"""Generates lib/l10n/app_strings{,_zh,_en}.dart from l10n_spec.py.

Run from anywhere:  python apps/desktop/tool/l10n/gen_l10n.py
Every key needs both a Chinese and an English text; the generated classes
make a missing translation a compile error.
"""
import os
import sys

sys.dont_write_bytecode = True  # keep __pycache__ out of the repository
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from l10n_spec import S  # noqa: E402

APP = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(APP, 'lib', 'l10n')
HEADER = (
    '// GENERATED by tool/l10n/gen_l10n.py from tool/l10n/l10n_spec.py.\n'
    '// Do not edit by hand.\n'
)

names = [e[0] for e in S if e[0] != '#']
dupes = {n for n in names if names.count(n) > 1}
if dupes:
    sys.exit(f'duplicate keys: {sorted(dupes)}')


def signature(name, params):
    return f'String get {name}' if not params else f'String {name}({params})'


def member(name, params, expr):
    sig = signature(name, params)
    one_line = f'  @override\n  {sig} => {expr};\n'
    if expr.startswith('switch') or (
        '\n' not in expr and len(f'  {sig} => {expr};') <= 80
    ):
        return one_line
    return f'  @override\n  {sig} =>\n      {expr};\n'


def abstract():
    out = [HEADER, '''
import 'package:flutter/widgets.dart';
import 'package:jianhe_core/jianhe_core.dart';

import 'app_language_scope.dart';
import 'app_strings_en.dart';
import 'app_strings_zh.dart';

/// Every user-facing string of the desktop app, in one language.
///
/// Widgets use [AppStrings.of] so they rebuild when the language changes.
/// Code without a BuildContext (platform services, error screens) uses
/// [AppStrings.current], which JianheApp keeps in step with the setting.
abstract class AppStrings {
  const AppStrings();

  static AppStrings forLanguage(AppLanguage language) => switch (language) {
    AppLanguage.zh => const ZhStrings(),
    AppLanguage.en => const EnStrings(),
  };

  static AppStrings _current = const ZhStrings();

  /// Strings for the language JianheApp currently shows.
  static AppStrings get current => _current;

  static void setCurrentLanguage(AppLanguage language) {
    _current = forLanguage(language);
  }

  /// Strings of the nearest [AppLanguageScope]; registers a dependency so the
  /// caller rebuilds when the language changes.
  static AppStrings of(BuildContext context) =>
      AppLanguageScope.maybeOf(context)?.strings ?? current;

  /// Like [of] without registering a dependency: safe in initState and in
  /// callbacks.
  static AppStrings read(BuildContext context) =>
      AppLanguageScope.read(context)?.strings ?? current;

  AppLanguage get language;
''']
    for name, params, zh, en in S:
        if name == '#':
            out.append(f'\n  // {params}\n')
            continue
        out.append(f'  {signature(name, params)};\n')
    out.append('}\n')
    return ''.join(out)


def impl(cls, lang, index, doc):
    out = [HEADER, f'''
import 'package:jianhe_core/jianhe_core.dart';

import 'app_strings.dart';

/// {doc}
class {cls} extends AppStrings {{
  const {cls}();

  @override
  AppLanguage get language => AppLanguage.{lang};
''']
    for entry in S:
        name, params = entry[0], entry[1]
        if name == '#':
            out.append(f'\n  // {params}\n')
            continue
        out.append(member(name, params, entry[index]))
    out.append('}\n')
    return ''.join(out)


os.makedirs(OUT, exist_ok=True)
files = {
    'app_strings.dart': abstract(),
    'app_strings_zh.dart': impl('ZhStrings', 'zh', 2, 'Simplified Chinese.'),
    'app_strings_en.dart': impl('EnStrings', 'en', 3, 'English.'),
}
for file, text in files.items():
    with open(os.path.join(OUT, file), 'w', encoding='utf-8', newline='\n') as handle:
        handle.write(text)
print(f'{len(names)} strings -> {OUT}')
